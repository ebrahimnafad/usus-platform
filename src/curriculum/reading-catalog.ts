const READING_LEVELS: Record<string, ReadingLevel> = {
  "level-1": READING_LEVEL_1,
  read_l1: READING_LEVEL_1,
  "1": READING_LEVEL_1,
};

/**
 * Resolves a reading level by its canonical id or alias.
 */
export function getReadingLevel(
  levelId: ReadingLevelId | string
): ReadingLevel | undefined {
  return READING_LEVELS[levelId];
}

/**
 * Resolves a specific reading story by level and story number or id.
 */
export function getReadingStory(
  levelId: ReadingLevelId | string,
  storyNumberOrId: number | string
): ReadingStory | undefined {
  const level = getReadingLevel(levelId);
  if (!level) return undefined;

  if (typeof storyNumberOrId === "number") {
    return level.stories.find((s) => s.storyNumber === storyNumberOrId);
  }

  const numericMatch = storyNumberOrId.match(/\d+/);
  const targetNum = numericMatch ? parseInt(numericMatch[0], 10) : NaN;

  return level.stories.find(
    (s) => s.id === storyNumberOrId || s.storyNumber === targetNum
  );
}
