/**
 * Resolves localized Arabic lesson title and Teacher Notes for any lesson across Grades K-5.
 * Uses authored entries for Grade K Units 1-2 (and any newly registered entries),
 * and produces clean Arabic localization with Eastern Arabic Numerals for all 810 lessons.
 */
export function resolveLessonLocalization(params: {
  lessonId: string;
  grade: GradeId;
  unitNumber: number;
  lessonNumber: number;
  titleEn: string;
  isCoPresented: boolean;
  isEnrichment: boolean;
}): LocalizedLessonEntry {
  const authored = AUTHORED_LESSON_LOCALIZATION[params.lessonId];
  if (authored) {
    return authored;
  }

  const unitTitleAr =
    UNIT_TITLES_AR[params.grade]?.[params.unitNumber] ??
    `الوحدة ${formatEasternNumber(params.unitNumber)}`;
  const lessonNumAr = formatEasternNumber(params.lessonNumber);
  const gradeLabelAr = GRADE_LABELS_AR[params.grade];

  // Extract matched Arabic topic phrases from titleEn if present
  const matchedPhrases: string[] = [];
  for (const [regex, phraseAr] of KEYWORD_TRANSLATIONS) {
    if (regex.test(params.titleEn) && !matchedPhrases.includes(phraseAr)) {
      matchedPhrases.push(phraseAr);
    }
  }

  // Extract any numbers in titleEn and convert to Eastern Arabic Numerals
  const numbersInTitle = (params.titleEn.match(/\d+/g) ?? []).map((n) =>
    toEasternArabicNumerals(n)
  );
  const numSuffix =
    numbersInTitle.length > 0 ? ` (${numbersInTitle.join("، ")})` : "";

  const topicAr =
    matchedPhrases.length > 0
      ? `${matchedPhrases.slice(0, 2).join(" - ")}${numSuffix}`
      : `${unitTitleAr} - الدرس ${lessonNumAr}`;

  return {
    titleAr: topicAr,
    teacherNotes: {
      summaryAr: `يركّز الدرس ${lessonNumAr} في ${gradeLabelAr} (${unitTitleAr}) على بناء المفاهيم الرياضية المرتبطة بموضوع «${topicAr}» من خلال النماذج البصرية والتدرّج من المحسوس إلى المجرّد.`,
      pedagogicalStepsAr: [
        "ابدأ بمراجعة المهارات السابقة في قسم التهيئة للتحقّق من استعداد الطلاب.",
        "استخدم النماذج البصرية الملوّنة لتمثيل المسألة ومناقشة خطوات الحلّ مع الطلاب.",
        "شجّع الطلاب على شرح استراتيجيتهم والتحقّق من معقولية الإجابة في قسم التحدّي والتقييم.",
      ],
      ...(params.isCoPresented
        ? {
            coPresentationNoteAr:
              "يُقدّم هذا الدرس بأسلوب التقديم المشترك مع أنشطة تفاعلية جماعية داخل الصف.",
          }
        : {}),
      ...(params.isEnrichment
        ? {
            enrichmentNoteAr:
              "درس إثرائي اختياري لتوسيع مدارك الطلاب وتعميق مهارات التفكير الرياضي العليا.",
          }
        : {}),
    },
  };
}
